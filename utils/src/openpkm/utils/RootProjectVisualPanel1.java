    private void setKnowledgeGraphs()
    {
        Neo4jProvider provider = Lookup.getDefault().lookup(Neo4jProvider.class);
        if(provider != null)
        {
            neo4jModel.removeAllElements();
            SortedSet<Neo4jInstance> instances = new TreeSet<Neo4jInstance>(Neo4jInstance.nameComparator());
            instances.addAll(provider.getInstances());
            neo4jModel.addAll(instances);
        }
    }
    
