    private void browse(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_browse
        String command = evt.getActionCommand();
        if ("BROWSE".equals(command)) {
            JFileChooser chooser = new JFileChooser();
            FileUtil.preventFileChooserSymlinkTraversal(chooser, null);
            chooser.setDialogTitle("Select Project Location");
            chooser.setFileSelectionMode(JFileChooser.DIRECTORIES_ONLY);
            String path = jTextField2.getText();
            if (path.length() > 0) {
                File f = new File(path);
                if (f.exists()) {
                    chooser.setSelectedFile(f);
                }
            }
            if (JFileChooser.APPROVE_OPTION == chooser.showOpenDialog(this)) {
                File projectDir = chooser.getSelectedFile();
                String absolutePath = FileUtil.normalizeFile(projectDir).getAbsolutePath();
                NbPreferences.forModule(RootProjectVisualPanel1.class).put("location", absolutePath);
                jTextField2.setText(absolutePath);
            }
            //panel.fireChangeEvent();
        }
    }//GEN-LAST:event_browse

